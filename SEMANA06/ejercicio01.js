// Función para calcular el área de un rectángulo
function calcularArea(base, altura) {
  return base * altura;
}

// Cálculo de las áreas utilizando la función
const area1 = calcularArea(10, 5);
const area2 = calcularArea(8, 3);
const area3 = calcularArea(12, 4);
const area4 = calcularArea(15, 6);

// Mostrar resultados
console.log("Área rectángulo 1:", area1);
console.log("Área rectángulo 2:", area2);
console.log("Área rectángulo 3:", area3);
console.log("Área rectángulo 4:", area4);
